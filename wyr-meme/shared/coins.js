export function sentimentFor(leftPct, leftCoin, rightCoin) {
  const l = COINS[leftCoin], r = COINS[rightCoin];
  const lead = leftPct >= 50 ? l : r;
  const pct = Math.max(leftPct, 100 - leftPct);
  if (pct < 53) return 'Dead heat — the crowd can’t decide! 🤝';
  if (lead.era === 'OG' && pct >= 65) return 'The crowd is bullish on nostalgia! 📼';
  if (lead.era === 'OG') return `Old school still has teeth — ${lead.ticker} leads. 🦴`;
  if (lead.concept) return `Degens are aping the hypothetical ${lead.ticker}. 🙈`;
  if (pct >= 65) return `New wave tsunami — ${lead.ticker} is mooning! 🌊`;
  return `Fresh blood edging ahead: ${lead.ticker}. 🌱`;
}
